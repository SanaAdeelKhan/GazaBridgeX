const excludedRoute = (pathname) => pathname === '/chat' || pathname.startsWith('/chat/');
const originalText = new Map();

function translateTree(root, language) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  let node;
  while ((node = walker.nextNode())) nodes.push(node);

  nodes.forEach((textNode) => {
    const parent = textNode.parentElement;
    if (!parent || ['SCRIPT', 'STYLE', 'INPUT', 'TEXTAREA', 'OPTION'].includes(parent.tagName)) return;
    if (parent.closest('[data-i18n-ignore]')) return;
    const current = textNode.nodeValue;
    const saved = originalText.get(textNode);
    const savedTranslation = saved && translations[saved.trim()];
    if (!saved || (current !== saved && current !== savedTranslation)) originalText.set(textNode, current);
    const original = originalText.get(textNode);
    if (original.includes('@')) return;
    const trimmed = original.trim();
    textNode.nodeValue = original;
    const translated = language === 'ar' ? translations[trimmed] : trimmed;
    if (!translated || translated === trimmed) return;
    const start = original.indexOf(trimmed);
    textNode.nodeValue = `${original.slice(0, start)}${translated}${original.slice(start + trimmed.length)}`;
  });
}

export default function AutoTranslate({ children }) {
  const { language } = useAppTranslation();
  const location = useLocation();

  useEffect(() => {
    if (excludedRoute(location.pathname)) return undefined;
    const observer = new MutationObserver(() => {
      observer.disconnect();
      translateTree(document.body, language);
      observer.observe(document.body, { childList: true, subtree: true });
    });
    translateTree(document.body, language);
    observer.observe(document.body, { childList: true, subtree: true });
    return () => observer.disconnect();
  }, [language, location.pathname]);

  return children;
}
